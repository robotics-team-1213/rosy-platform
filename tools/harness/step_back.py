"""Step-back check: a PR must not silently undo lines another PR merged into main recently.

Usage:
    python tools/harness/step_back.py --base origin/main [--head HEAD] [--body-file F] [--days 7]

Two levels. BLOCK (the PR body must say "Replaces: #N (why)" or "Step-Back: none (why)"): a merge of main inside the
branch dropped recent main lines that the branch never repaired, the PR removes recent lines from a file that shrinks
while no own commit deleted them in that path, or the PR is too big to check. INFO (printed, never blocks): every other
rewrite of a recent PR's lines. A git failure is loud: exit 2 with "scan incomplete" and the command. Only a blame
failure on one file is a warning that keeps the blocks already confirmed.
Size limits (30 counted files, 20 own commits, 7 day merge base) block unless the body has "Size-Exception: <reason>".
What it cannot see (squash, rebase, an older file copied in an ordinary commit give INFO only): shared-checkout.md.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import time
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

MAX_LINES, MAX_FILES, MAX_MERGES, MAX_MERGE_FILES = 3000, 150, 40, 400
# Generated and record paths: renumbered or regenerated by tools, never a step back (D-1061).
SKIP_NAMES = {"logs.md", "STATUS.md", "contract_version.py", "known_failures.txt", "adr_gaps.txt", "ROSY ADR Log.md",
              "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock", "Cargo.lock"}
SKIP_PATH = re.compile(r"((^|/)index\.md$|^docs/reference/api-changes/|(^|/)logs/\d{4}/\d{2}/|\.lock(\.\w+)?$)")
# Per-line skips inside a file that has substantive text too: the API reference renumbers only these rows (D-1061).
LINE_SKIP = {"ROSY API & Protocol Reference.md": re.compile(r"^\*\*Version:\*\*|\bv1\.next\b|^\| v\d+\.\d+ \|")}
CPP_DIRECTIVE = re.compile(r"#\s*(include|define|undef|if|ifdef|ifndef|elif|else|endif|pragma)\b")
HUNK = re.compile(r"@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")


class ScanError(RuntimeError):
    """A git call failed: the scan is incomplete and must not read as a pass."""


def git(repo, *args: str, soft: bool = False) -> str:
    r = subprocess.run(["git", "-C", str(repo), "-c", "core.quotepath=off", *args], capture_output=True)
    if r.returncode and not soft:
        raise ScanError(f"git {' '.join(args)[:300]} failed ({r.returncode}): {r.stderr.decode('utf-8', errors='replace').strip()}")
    return r.stdout.decode("utf-8", errors="replace")


def names(repo, *args: str) -> list[str]:
    return [x for x in git(repo, "diff", "--name-only", "-z", *args).split("\0") if x]


def merge_base(repo, a: str, b: str) -> str:
    out = git(repo, "merge-base", a, b, soft=True).strip()
    if not out:
        raise ScanError(f"git merge-base {a} {b}: no merge base (unrelated or shallow history; fetch full history)")
    return out


def is_ancestor(repo, a: str, b: str) -> bool:
    return subprocess.run(["git", "-C", str(repo), "merge-base", "--is-ancestor", a, b], capture_output=True).returncode == 0


def skipped(path: str) -> bool:
    return path.rsplit("/", 1)[-1] in SKIP_NAMES or bool(SKIP_PATH.search(path))


def comment_or_blank(path: str, text: str) -> bool:
    s = text.strip()
    if not s:
        return True
    pat = LINE_SKIP.get(path.rsplit("/", 1)[-1])
    if pat and pat.search(s):
        return True
    if path.endswith(".md"):
        return s.startswith("<!--")
    return s.startswith(("//", "/*", "*", "<!--")) or (s.startswith("#") and not CPP_DIRECTIVE.match(s))


def _unquote(p: str) -> str:
    """Git quotes a path with a quote, backslash or control character in a diff header."""
    p = p.split("\t")[0]
    if p.startswith('"') and p.endswith('"'):
        p = p[1:-1].replace("\\t", "\t").replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")
    return p


def parse_hunks(diff: str, texts: dict | None = None) -> dict[tuple[str, str], list[tuple[int, int, int, int]]]:
    """(old path, new path) -> (old start, old count, new start, new count). Parsed by hunk counts: a deleted '-- x' line is safe.
    With texts, also (old path, new path) -> the deleted lines."""
    out: dict[tuple[str, str], list[tuple[int, int, int, int]]] = {}
    lines, i, old, new = diff.split("\n"), 0, None, None
    while i < len(lines):
        ln = lines[i]
        i += 1
        if ln.startswith("--- "):
            old = "" if ln[4:].startswith("/dev/null") else _unquote(ln[4:]).removeprefix("a/")
        elif ln.startswith("+++ "):
            new = "" if ln[4:].startswith("/dev/null") else _unquote(ln[4:]).removeprefix("b/")
        elif ln.startswith("@@") and old is not None and new is not None and (m := HUNK.match(ln)):
            h = tuple(int(1 if g is None else g) for g in m.groups())
            out.setdefault((old, new), []).append(h)
            if texts is not None:
                texts.setdefault((old, new), []).extend(x[1:] for x in lines[i:i + h[1]])
            i += h[1] + h[3]
            while i < len(lines) and lines[i].startswith("\\"):
                i += 1
    return out


def blame_commits(repo, rev: str, path: str, nums: list[int]) -> dict[int, str]:
    """line number -> introducing commit; one blame per 200 ranges of one file."""
    out: dict[int, str] = {}
    for k in range(0, len(nums), 200):
        args = [x for n in nums[k:k + 200] for x in ("-L", f"{n},{n}")]
        for m in re.finditer(r"^([0-9a-f]{40}) \d+ (\d+)", git(repo, "blame", "--porcelain", *args, rev, "--", path), re.M):
            out[int(m.group(2))] = m.group(1)
    return out


def pr_of_commits(repo, base_ref: str, commits: set[str], since: float) -> dict[str, tuple[int, int]]:
    """commit -> (PR number, merge time): the first-parent 'Merge pull request #N' of base history that brought it in.
    The PR merge commit itself counts too: its conflict-resolution edits blame to it."""
    found: dict[str, tuple[int, int]] = {}
    if not commits:
        return found
    merges: list[tuple[str, str, int, int]] = []
    for row in git(repo, "log", "--first-parent", "--merges", f"--since={int(since)}", "--format=%H %P|%ct|%s", base_ref).splitlines():
        ids, ct, subj = row.split("|", 2)
        merge, *parents = ids.split()
        m = re.match(r"Merge pull request #(\d+)", subj)
        if m and len(parents) == 2:
            merges.append((merge, parents[0], int(m.group(1)), int(ct)))
    if not merges:
        return found
    oldest_p0 = merges[-1][1]
    parents_of = {p[0]: p[1:] for ln in git(repo, "rev-list", "--parents", f"{oldest_p0}..{base_ref}").splitlines()
                  if (p := ln.split())}
    cur = git(repo, "rev-parse", f"{base_ref}^{{commit}}").strip()
    first_chain: list[str] = []
    while cur and cur != oldest_p0 and cur in parents_of:
        first_chain.append(cur)
        cur = parents_of[cur][0] if parents_of[cur] else ""
    merge_meta = {m: (pr, ct) for m, _, pr, ct in merges}
    seen_on_main: set[str] = set()
    for u in reversed(first_chain):
        ps = parents_of.get(u, ())
        brought: list[str] = []
        if len(ps) > 1:
            stack = [p for p in ps[1:] if p in parents_of and p not in seen_on_main]
            while stack:
                x = stack.pop()
                if x in seen_on_main:
                    continue
                seen_on_main.add(x)
                brought.append(x)
                for p in parents_of.get(x, ()):
                    if p in parents_of and p not in seen_on_main:
                        stack.append(p)
        seen_on_main.add(u)
        if info := merge_meta.get(u):
            if u in commits:
                found.setdefault(u, info)
            for c in brought:
                if c in commits:
                    found.setdefault(c, info)
    return found


def _hit(level: str, why: str, pr, when: dict, path: str, n: int) -> dict:
    stamp = datetime.fromtimestamp(when[pr], timezone.utc).strftime("%Y-%m-%d %H:%M") if pr in when else ""
    return {"level": level, "why": why, "pr": pr, "merged_at": stamp, "path": path, "lines": n}


def _warn(msg: str) -> dict:
    return {"level": "warn", "why": msg, "pr": None, "merged_at": "", "path": msg, "lines": 0}


def _big(msg: str, n: int = 0) -> dict:
    return {"level": "block", "why": "too big", "pr": None, "merged_at": "", "path": msg, "lines": n}


def final_paths(repo, a: str, b: str) -> dict[str, str]:
    """Path in a -> path in b for renames, "" for deletions (rename-aware, -z)."""
    toks, out, i = git(repo, "diff", "-M", "--name-status", "-z", a, b).split("\0"), {}, 0
    while i < len(toks) and toks[i]:
        st = toks[i][0]
        if st in "RC":
            if st == "R":
                out[toks[i + 1]] = toks[i + 2]
            i += 3
        else:
            if st == "D":
                out[toks[i + 1]] = ""
            i += 2
    return out


def merge_drops(repo, base_ref: str, head_ref: str, days: int, now: float) -> list[dict]:
    """BLOCK 1: main lines a main-merge inside the branch dropped and the branch never repaired. Lines the main side added
    (vs the merge's own merge-base) that are absent from the merge result AND from the final tree, whose PR merged within days."""
    since, hits = now - days * 86400, []
    rows = git(repo, "rev-list", "--merges", "--parents", f"{base_ref}..{head_ref}").splitlines()
    if len(rows) > MAX_MERGES:
        return [_big(f"too big to check: {len(rows)} merges inside the branch (cap {MAX_MERGES}); merge scan skipped", len(rows))]
    for row in rows:
        m, *parents = row.split()
        main_side = [p for p in parents if is_ancestor(repo, p, base_ref)]
        if len(parents) != 2 or len(main_side) != 1:
            continue
        pm, pb = main_side[0], next(p for p in parents if p != main_side[0])
        mb = merge_base(repo, pm, pb)
        both = sorted(f for f in set(names(repo, mb, pm)) & set(names(repo, mb, pb)) if not skipped(f))
        if len(both) > MAX_MERGE_FILES:
            hits.append(_big(f"too big to check: merge {m[:10]} changed {len(both)} files on both sides (cap {MAX_MERGE_FILES})", len(both)))
            continue
        fmap: dict[str, str] | None = None
        dropped: dict[str, dict[int, str]] = {}
        for k in range(0, len(both), 100):
            for (old, new), hs in parse_hunks(git(repo, "diff", "-U0", "--no-color", "--no-renames", mb, pm, "--", *both[k:k + 100])).items():
                if not new:
                    continue
                text = git(repo, "show", f"{pm}:{new}", soft=True).split("\n")
                kept = {x.strip() for x in git(repo, "show", f"{m}:{new}", soft=True).split("\n")}
                nums = [n for _, _, s, c in hs for n in range(s, s + c) if not comment_or_blank(new, text[n - 1]) and text[n - 1].strip() not in kept]
                if nums:
                    fmap = final_paths(repo, pm, head_ref) if fmap is None else fmap
                    final = fmap.get(new, new)
                    kept_final = {x.strip() for x in git(repo, "show", f"{head_ref}:{final}", soft=True).split("\n")} if final else set()
                    nums = [n for n in nums if text[n - 1].strip() not in kept_final]  # repaired later in the branch: no block
                if nums:
                    try:
                        dropped[new] = blame_commits(repo, pm, new, nums)
                    except ScanError as e:
                        hits.append(_warn(f"blame failed on {new}, file skipped: {e}"))
        prs = pr_of_commits(repo, base_ref, {c for v in dropped.values() for c in v.values()}, since)
        when = {p: t for p, t in prs.values()}
        for path, lines in dropped.items():
            for pr in sorted({prs[c][0] for c in lines.values() if c in prs}):
                hits.append(_hit("block", "a merge of main in this branch dropped these lines", pr, when, path,
                                 sum(1 for c in lines.values() if c in prs and prs[c][0] == pr)))
    return hits


def report(repo, base_ref: str, head_ref: str, days: int = 7, max_lines: int = MAX_LINES, max_files: int = MAX_FILES,
           now: float | None = None) -> list[dict]:
    """Hits {level, why, pr, merged_at, path, lines}; level is block, info or warn. Raises ScanError when git fails."""
    if git(repo, "rev-parse", "--is-shallow-repository").strip() == "true":
        raise ScanError("shallow clone: fetch full history first (git fetch --unshallow)")
    for ref in (base_ref, head_ref):
        git(repo, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}")
    base = merge_base(repo, base_ref, head_ref)
    now = time.time() if now is None else now
    changed = names(repo, "-M", base, head_ref)  # every changed file, also binary and mode-only
    hunks = {k: v for k, v in parse_hunks(git(repo, "diff", "-M", "-U0", "--no-color", base, head_ref)).items() if not skipped(k[0])}
    total = sum(h[1] for v in hunks.values() for h in v)
    if total > max_lines or len(changed) > max_files:
        note = f"too big to check: {total} deleted lines, {len(changed)} changed files (cap {max_lines} lines, {max_files} files); split the PR"
        return [_big(note, total)] + merge_drops(repo, base_ref, head_ref, days, now)  # the targeted check stays cheap on a huge diff
    warns: list[dict] = []
    cands: dict[str, dict[int, str]] = {}  # old path -> line number -> commit
    texts: dict[str, list[str]] = {}
    shrinks: set[str] = set()
    for (old, new), hs in hunks.items():
        text = git(repo, "show", f"{base}:{old}", soft=True)
        if "\0" in text:
            continue
        newtext = git(repo, "show", f"{head_ref}:{new}", soft=True) if new else ""
        kept = {x.strip() for x in newtext.split("\n")} if new else set()
        if not new or len(newtext.split("\n")) < len(text.split("\n")):
            shrinks.add(old)
        old_lines = texts[old] = text.split("\n")
        nums = [n for s, c, _, _ in hs for n in range(s, s + c)
                if not comment_or_blank(old, old_lines[n - 1]) and old_lines[n - 1].strip() not in kept]
        if nums:
            try:
                cands[old] = blame_commits(repo, base, old, nums)
            except ScanError as e:
                warns.append(_warn(f"blame failed on {old}, file skipped: {e}"))
    prs = pr_of_commits(repo, base_ref, {c for m in cands.values() for c in m.values()}, now - days * 86400)
    when = {p: t for p, t in prs.values()}
    own: Counter | None = None
    blocks, infos = merge_drops(repo, base_ref, head_ref, days, now), []
    for path, m in sorted(cands.items()):
        recent = {n: prs[c][0] for n, c in m.items() if c in prs}
        if path in shrinks and recent and own is None:  # BLOCK 2: what own non-merge commits deleted, per path
            own, dels = Counter(), {}
            for seg in git(repo, "log", "--no-merges", "-p", "-U0", "-M", "--no-color", "--format=%x00", f"{base_ref}..{head_ref}").split("\0"):
                dels.clear()
                parse_hunks(seg, dels)
                own.update((o, t.strip()) for (o, _), ts in dels.items() for t in ts)
        for pr in sorted(set(recent.values())):
            mine = [n for n, p in recent.items() if p == pr]
            orphan = 0
            for n in mine:
                key = (path, texts[path][n - 1].strip())
                if own is not None and own[key] > 0:
                    own[key] -= 1
                else:
                    orphan += 1
            if path in shrinks and orphan:
                blocks.append(_hit("block", "removed with no own commit deleting it in this path", pr, when, path, orphan))
            infos.append(_hit("info", "rewrote lines of a recent PR", pr, when, path, len(mine)))
    keys = {(h["pr"], h["path"]) for h in blocks}
    return blocks + [h for h in infos if (h["pr"], h["path"]) not in keys] + warns


def acknowledged(body_text: str, prs) -> set:
    """The PRs of prs the body names: 'Replaces: #N[, #M] (reason)' lines, or 'Step-Back: none (reason)' for all (None too)."""
    ok: set = set()
    for line in (body_text or "").splitlines():
        line = line.strip().lstrip("-*> ").strip()
        if re.fullmatch(r"Step-Back:\s*none\s*\(\s*\S.*\)", line, re.I):
            return set(prs)
        m = re.fullmatch(r"Replaces:\s*(.+?)\s*\(\s*(\S.*)\)", line, re.I)
        if m and re.fullmatch(r"#\d+(?:\s*(?:,|and|&)?\s*#\d+)*", m.group(1)):
            ok |= {int(n) for n in re.findall(r"#(\d+)", m.group(1))}
    return ok & set(prs)


SIZE_EXCEPTION = re.compile(r"Size-Exception:\s*\S.*", re.I)


def counted_files(repo, base: str, head_ref: str) -> int:
    """Changed files that count toward the limit: not generated or record paths (skip list), not pure renames."""
    toks, n, i = git(repo, "diff", "-M", "--name-status", "-z", base, head_ref).split("\0"), 0, 0
    while i < len(toks) and toks[i]:
        st = toks[i]
        step = 3 if st[0] in "RC" else 2
        if not (st == "R100" or skipped(toks[i + step - 1])):
            n += 1
        i += step
    return n


def size_violations(repo, base_ref: str, head_ref: str, now: float | None = None) -> list[str]:
    """Counted changed files > 30, own non-merge commits > 20, merge-base older than 7 days (rule 4, blocking since D-1067). No branch is exempt by name."""
    try:
        base = merge_base(repo, base_ref, head_ref)
        now = time.time() if now is None else now
        files = counted_files(repo, base, head_ref)
        commits = int(git(repo, "rev-list", "--no-merges", "--count", f"{base_ref}..{head_ref}").strip() or 0)
        age = (now - int(git(repo, "log", "-1", "--format=%ct", base).strip() or now)) / 86400
    except ScanError as e:
        return [f"size check incomplete: {e}"]
    return [w for ok, w in ((files > 30, f"{files} changed files (limit 30)"), (commits > 20, f"{commits} own non-merge commits (limit 20)"),
                            (age > 7, f"merge-base is {age:.0f} days old (limit 7)")) if ok]


def size_excepted(body: str) -> bool:
    """The PR body carries a 'Size-Exception: <reason>' line with a non-empty reason."""
    return any(SIZE_EXCEPTION.fullmatch(line.strip().lstrip("-*> ").strip()) for line in (body or "").splitlines())


def blocking(hits: list[dict], body: str) -> list[dict]:
    """Block-level hits the PR body does not name."""
    blocks = [h for h in hits if h["level"] == "block"]
    ok = acknowledged(body, {h["pr"] for h in blocks})
    return [h for h in blocks if h["pr"] not in ok]


def fmt(h: dict) -> str:
    if h["pr"] is None:
        return f"  {h['path']}"
    return f"  #{h['pr']} (merged {h['merged_at']} UTC): {h['path']} ({h['lines']} lines) - {h['why']}"


def explain(bad: list[dict]) -> str:
    prs = sorted({h["pr"] for h in bad if h["pr"] is not None})
    fixes = ([f"Replaces: {', '.join(f'#{p}' for p in prs)} (why these lines go)"] if prs else []) + (
        ["Step-Back: none (why the size is fine)"] if any(h["pr"] is None for h in bad) else [])
    return "\n".join(fmt(h) for h in bad) + "\nAdd to the PR body:\n  " + "\n  ".join(fixes) + "\n(Step-Back: none (reason) acknowledges every hit, size included)"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--base", required=True)
    p.add_argument("--head", default="HEAD")
    p.add_argument("--body-file", default="")
    p.add_argument("--days", type=int, default=7)
    p.add_argument("--repo", default=str(Path(__file__).resolve().parents[2]))
    a = p.parse_args(argv)
    body = Path(a.body_file).read_text(encoding="utf-8", errors="replace").strip() if a.body_file else ""
    try:
        hits = report(a.repo, a.base, a.head, a.days)
    except ScanError as e:
        print(f"[step-back] scan incomplete: {e}", file=sys.stderr)
        return 2
    bad = blocking(hits, body)
    info = [h for h in hits if h["level"] == "info"]
    print(f"[step-back] {len(bad)} unacknowledged block, {len([h for h in hits if h['level'] == 'block']) - len(bad)} acknowledged, {len(info)} info")
    for h in (h for h in hits if h["level"] == "warn"):
        print(f"[step-back] warning, scan incomplete for one file: {h['path']}")
    if info:
        print("info (never blocks):\n" + "\n".join(fmt(h) for h in info))
    if bad:
        print("BLOCK:\n" + explain(bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
